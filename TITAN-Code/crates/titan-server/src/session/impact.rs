//! Change impact analysis: what is known to be related to a symbol or position?
//!
//! The answer is grouped by how it is known, never merged:
//! * **known** — rust-analyzer: the definition, references, and callers (call hierarchy),
//!   for exactly the requested document revision;
//! * **structural** — the project graph: containing module and package, modules importing
//!   it, packages depending on it, tests linked to the module or package;
//! * **heuristic** — definitions with the same name from the syntax index (candidates);
//! * **unknown** — what no source here can see (macros, dynamic dispatch, code outside the
//!   workspace, unreported uses in other languages or build scripts).
//!
//! The analysis is not exhaustive and says so (`coverage.complete` is always false).

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};
use std::time::Instant;

use serde_json::{Value, json};
use titan_index::graph::{EdgeKind, NodeId, NodeKind};
use titan_lsp::LspError;
use titan_protocol::messages::{Evidence, PositionParams};

use super::intel::{Part, Query};
use super::lsp::LspPending;
use super::{Reply, Session};

pub(super) const UNKNOWN: &[&str] = &[
    "uses generated by macros or build scripts",
    "dynamic dispatch: implementations reached through trait objects are not callers of the trait method",
    "code outside the workspace (dependents in other repositories)",
    "uses from other languages, configuration files or reflection-like string lookups",
];

pub(super) struct ImpactJob {
    pub id: Option<Value>,
    pub doc_id: u64,
    pub revision: u64,
    pub path: PathBuf,
    pub line: usize,
    pub generation: u64,
    pub started: Instant,
    pub remaining: usize,
    pub heuristic: Evidence,
    pub parts: BTreeMap<&'static str, Result<Value, String>>,
}

pub(super) enum Job {
    Impact(Box<ImpactJob>),
    Rename(Box<super::refactor::RenameJob>),
}

impl Job {
    /// The client request waiting for this job.
    pub(super) fn request_id(self) -> Option<Value> {
        match self {
            Self::Impact(j) => j.id,
            Self::Rename(j) => j.id,
        }
    }
}

fn part_name(part: Part) -> &'static str {
    match part {
        Part::Definition => "definition",
        Part::References => "references",
        Part::PrepareCallHierarchy => "prepareCallHierarchy",
        Part::IncomingCalls => "incomingCalls",
        Part::PrepareRename => "prepareRename",
        Part::Rename => "rename",
    }
}

impl Session {
    /// Send one part of a job; returns false if it could not be sent.
    pub(super) fn send_part(
        &mut self,
        job: u64,
        part: Part,
        params: Value,
        doc_id: u64,
        revision: u64,
    ) -> bool {
        let Some(supervisor) = &self.semantic.supervisor else {
            return false;
        };
        let query = Query::Part { job, part };
        match supervisor.request(query.method(), params, None) {
            Ok(ticket) => {
                self.semantic.pending.insert(
                    ticket,
                    LspPending {
                        id: None,
                        key: None,
                        query,
                        doc_id: Some(doc_id),
                        revision: Some(revision),
                        generation: self.semantic.generation,
                        started: Instant::now(),
                        syntax: Vec::new(),
                    },
                );
                true
            }
            Err(_) => false,
        }
    }

    pub(super) fn twin_impact(&mut self, params: PositionParams, id: Option<Value>) -> Reply {
        let (lsp, offset) = match self.prepare_position(Query::References, &params) {
            Ok(p) => p,
            Err(e) => return Reply::Now(Err(e)),
        };
        let Some(od) = self.documents.get(&params.document_id) else {
            return Reply::Now(Err(super::rpc_error(
                titan_protocol::rpc::codes::DOCUMENT_NOT_FOUND,
                "document is not open",
            )));
        };
        let path = od.doc.path().to_path_buf();
        let heuristic = self.name_match_evidence(params.document_id, offset);
        self.semantic.next_job += 1;
        let job = self.semantic.next_job;
        let mut impact = ImpactJob {
            id,
            doc_id: params.document_id,
            revision: params.expected_revision,
            path,
            line: params.position.line,
            generation: self.semantic.generation,
            started: Instant::now(),
            remaining: 0,
            heuristic,
            parts: BTreeMap::new(),
        };
        let blocked = self.semantic_blocker(Some(params.document_id), Query::Definition);
        if blocked.is_none() {
            let mut refs = lsp.clone();
            refs["context"] = json!({ "includeDeclaration": true });
            for (part, p) in [
                (Part::Definition, lsp.clone()),
                (Part::References, refs),
                (Part::PrepareCallHierarchy, lsp),
            ] {
                let supported = self
                    .semantic_blocker(Some(params.document_id), Query::Part { job, part })
                    .is_none();
                if supported
                    && self.send_part(job, part, p, params.document_id, params.expected_revision)
                {
                    impact.remaining += 1;
                } else {
                    impact.parts.insert(
                        part_name(part),
                        Err("not supported by the language server".to_string()),
                    );
                }
            }
        }
        if impact.remaining == 0 {
            let reason = blocked.unwrap_or_else(|| "no request could be sent".to_string());
            for part in [Part::Definition, Part::References, Part::IncomingCalls] {
                impact
                    .parts
                    .entry(part_name(part))
                    .or_insert(Err(reason.clone()));
            }
            let value = self.impact_result(&impact);
            return Reply::Now(Ok(value));
        }
        self.semantic
            .jobs
            .insert(job, Job::Impact(Box::new(impact)));
        Reply::Deferred
    }

    pub(super) fn on_job_part(
        &mut self,
        job: u64,
        part: Part,
        _generation: u64,
        result: Result<Value, LspError>,
    ) {
        match self.semantic.jobs.remove(&job) {
            Some(Job::Impact(impact)) => self.on_impact_part(job, *impact, part, result),
            Some(Job::Rename(rename)) => self.on_rename_part(job, *rename, part, result),
            None => {}
        }
    }

    fn on_impact_part(
        &mut self,
        job: u64,
        mut impact: ImpactJob,
        part: Part,
        result: Result<Value, LspError>,
    ) {
        impact.remaining = impact.remaining.saturating_sub(1);
        match (part, result) {
            (Part::PrepareCallHierarchy, Ok(items)) => {
                let item = items.as_array().and_then(|a| a.first()).cloned();
                match item {
                    Some(item)
                        if self.send_part(
                            job,
                            Part::IncomingCalls,
                            json!({ "item": item }),
                            impact.doc_id,
                            impact.revision,
                        ) =>
                    {
                        impact.remaining += 1;
                    }
                    Some(_) => {
                        impact.parts.insert(
                            "incomingCalls",
                            Err("could not send the request".to_string()),
                        );
                    }
                    None => {
                        impact
                            .parts
                            .insert("incomingCalls", Ok(Value::Array(Vec::new())));
                    }
                }
            }
            (Part::PrepareCallHierarchy, Err(e)) => {
                impact.parts.insert("incomingCalls", Err(e.to_string()));
            }
            (part, result) => {
                impact
                    .parts
                    .insert(part_name(part), result.map_err(|e| e.to_string()));
            }
        }
        if impact.remaining > 0 {
            self.semantic
                .jobs
                .insert(job, Job::Impact(Box::new(impact)));
            return;
        }
        let value = self.impact_result(&impact);
        if let Some(id) = impact.id.clone() {
            self.respond(id, Ok(value));
        }
    }

    fn semantic_section(
        &self,
        impact: &ImpactJob,
        name: &str,
        current: bool,
        items: impl FnOnce(&Value) -> Vec<Value>,
    ) -> Value {
        match impact.parts.get(name) {
            Some(Ok(value)) => json!({
                "status": if current { "current" } else { "stale" },
                "items": items(value),
            }),
            Some(Err(e)) => json!({ "status": "unavailable", "error": e, "items": [] }),
            None => json!({ "status": "unavailable", "items": [] }),
        }
    }

    fn impact_result(&self, impact: &ImpactJob) -> Value {
        let current_revision = self
            .documents
            .get(&impact.doc_id)
            .map(|od| od.doc.text().revision());
        let current = current_revision == Some(impact.revision)
            && impact.generation == self.semantic.generation;
        let definitions =
            self.semantic_section(impact, "definition", current, |v| self.locations(v));
        let references =
            self.semantic_section(impact, "references", current, |v| self.locations(v));
        let callers = self.semantic_section(impact, "incomingCalls", current, |v| {
            v.as_array()
                .into_iter()
                .flatten()
                .filter_map(|call| {
                    let from = &call["from"];
                    let location = self.location_json(
                        from["uri"].as_str()?,
                        &from["selectionRange"],
                        &mut Default::default(),
                    )?;
                    Some(json!({
                        "name": from["name"],
                        "location": location,
                        "callSites": call["fromRanges"].as_array().map_or(0, Vec::len),
                    }))
                })
                .collect()
        });

        // Anchor for the structural part: the semantic definition when known, else the
        // queried position.
        let anchor = definitions["items"]
            .as_array()
            .and_then(|a| a.first())
            .and_then(|d| {
                let path = d["path"].as_str()?;
                let line = d["range"]["start"]["line"].as_u64()? as usize;
                (d["external"] == false).then(|| (PathBuf::from(path), line))
            })
            .or_else(|| {
                let rel = self.workspace.as_ref()?.relative(&impact.path)?;
                Some((rel, impact.line))
            });
        let structural = anchor
            .as_ref()
            .map(|(path, line)| self.structural_impact(path, *line))
            .unwrap_or_else(
                || json!({ "status": "unavailable", "error": "no anchor in the workspace" }),
            );

        // Affected files with reasons.
        let mut files: BTreeMap<String, BTreeSet<&'static str>> = BTreeMap::new();
        let mut add = |list: &Value, key: &str, reason: &'static str| {
            for item in list.as_array().into_iter().flatten() {
                let loc = if key.is_empty() { item } else { &item[key] };
                if loc["external"] == true {
                    continue;
                }
                if let Some(p) = loc["path"].as_str() {
                    files.entry(p.to_string()).or_default().insert(reason);
                }
            }
        };
        add(&definitions["items"], "", "definition");
        add(&references["items"], "", "reference");
        add(&callers["items"], "location", "caller");
        add(&structural["importers"], "", "importsModule");
        add(&structural["tests"], "", "test");
        if let Some(m) = structural.get("module") {
            add(&json!([m]), "", "containingModule");
        }
        let affected: Vec<Value> = files
            .into_iter()
            .map(|(path, reasons)| {
                let abs = self.workspace.as_ref().map(|ws| ws.root().join(&path));
                let doc = abs.as_ref().and_then(|a| self.by_path.get(a)).copied();
                let diagnostics = doc.and_then(|d| self.semantic_diagnostics_params(d)).map(|p| {
                    json!({
                        "current": p.current,
                        "revision": p.revision,
                        "errors": p.diagnostics.iter().filter(|d| d.severity == "error").count(),
                        "warnings": p.diagnostics.iter().filter(|d| d.severity == "warning").count(),
                    })
                });
                json!({
                    "path": path,
                    "reasons": reasons,
                    "openRevision": doc.and_then(|d| self.documents.get(&d)).map(|od| od.doc.text().revision()),
                    "semanticDiagnostics": diagnostics,
                })
            })
            .collect();

        json!({
            "target": {
                "documentId": impact.doc_id,
                "revision": impact.revision,
                "currentRevision": current_revision,
                "path": self.relative_display(&impact.path),
                "line": impact.line,
            },
            "known": {
                "source": self.semantic_name(),
                "generation": impact.generation,
                "complete": self.semantic.quiescent(),
                "definitions": definitions,
                "references": references,
                "callers": callers,
            },
            "structural": structural,
            "heuristic": {
                "nameMatches": impact.heuristic,
            },
            "affectedFiles": affected,
            "coverage": {
                "complete": false,
                "semantic": if current { "current" } else { "stale" },
                "graph": self.graph_header(),
                "limitations": self.semantic_limitations(),
                "unknown": UNKNOWN,
            },
            "elapsedMs": impact.started.elapsed().as_millis() as u64,
        })
    }

    /// Graph relations around `line` of workspace-relative `path`.
    fn structural_impact(&self, path: &Path, line: usize) -> Value {
        let Some(graph) = self.graph.graph.as_deref() else {
            return json!({ "status": "unavailable", "error": "the project graph is not built yet" });
        };
        let symbol = graph
            .nodes_in_file(path)
            .into_iter()
            .find(|n| n.kind != NodeKind::Module && n.start.is_some_and(|s| s.line == line));
        let module: Option<NodeId> = symbol
            .and_then(|s| {
                graph
                    .incoming(s.id)
                    .into_iter()
                    .find(|e| matches!(e.kind, EdgeKind::Defines | EdgeKind::Contains))
                    .map(|e| e.from)
            })
            .or_else(|| graph.module_at(path, line));
        let Some(module) = module else {
            return json!({ "status": "unavailable", "error": "the position is not in the module tree" });
        };
        // Walk up to the package.
        let mut package = None;
        let mut at = module;
        for _ in 0..64 {
            let parents: Vec<_> = graph
                .incoming(at)
                .into_iter()
                .filter(|e| e.kind == EdgeKind::Contains)
                .collect();
            let Some(parent) = parents.first() else { break };
            if graph
                .node(parent.from)
                .is_some_and(|n| n.kind == NodeKind::Package)
            {
                package = Some(parent.from);
                break;
            }
            at = parent.from;
        }
        let node = |id: NodeId| graph.node(id).map(|n| self.node_json(n));
        let with_edge = |e: &titan_index::graph::GraphEdge, other: NodeId| {
            let mut v = node(other).unwrap_or(Value::Null);
            v["edge"] = self.edge_json(e);
            v
        };
        let importers: Vec<Value> = graph
            .incoming(module)
            .iter()
            .filter(|e| e.kind == EdgeKind::Imports)
            .map(|e| with_edge(e, e.from))
            .collect();
        let mut tests: Vec<Value> = graph
            .incoming(module)
            .iter()
            .filter(|e| e.kind == EdgeKind::Tests)
            .map(|e| with_edge(e, e.from))
            .collect();
        let mut dependents = Vec::new();
        if let Some(pkg) = package {
            tests.extend(
                graph
                    .incoming(pkg)
                    .iter()
                    .filter(|e| e.kind == EdgeKind::Tests)
                    .map(|e| with_edge(e, e.from)),
            );
            dependents = graph
                .incoming(pkg)
                .iter()
                .filter(|e| e.kind == EdgeKind::DependsOn)
                .map(|e| with_edge(e, e.from))
                .collect();
        }
        json!({
            "status": "ok",
            "symbol": symbol.map(|s| self.node_json(s)),
            "module": node(module),
            "package": package.and_then(node),
            "importers": importers,
            "tests": tests,
            "dependents": dependents,
            "note": "tests are linked by test attributes and module layout (cfg(test) parent, tests/ targets), not by coverage",
        })
    }
}
